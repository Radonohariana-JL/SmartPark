    /** Mini jauge de progression dessinee en vectoriel. */
    private static class Jauge extends JPanel {

        private final double pourcentage;

        Jauge(double pourcentage) {
            this.pourcentage = Math.max(0, Math.min(1, pourcentage));
            setOpaque(false);
            setPreferredSize(new Dimension(80, 6));
            setMinimumSize(new Dimension(40, 6));
        }

        @Override
        protected void paintComponent(Graphics g) {
            Graphics2D g2 = (Graphics2D) g.create();
            g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING,
                    RenderingHints.VALUE_ANTIALIAS_ON);

            int w = getWidth();
            int h = getHeight();
            g2.setColor(BORDURE_FORTE);
            g2.fillRoundRect(0, 0, w, h, h, h);

            int pleine = (int) Math.round(w * pourcentage);
            if (pleine > 0) {
                g2.setPaint(new GradientPaint(0, 0, BLEU, pleine, 0, CYAN));
                g2.fillRoundRect(0, 0, Math.max(pleine, h), h, h, h);
            }
            g2.dispose();
        }
    }

