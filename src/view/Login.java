    /** Panneau a fond arrondi + bordure fine, dessine avec antialiasing. */
    private static class FondArrondi extends JPanel {

        private final Color fond;
        private final Color bordure;
        private final int rayon;

        FondArrondi(Color fond, Color bordure, int rayon) {
            this.fond = fond;
            this.bordure = bordure;
            this.rayon = rayon;
            setOpaque(false);
        }

        @Override
        protected void paintComponent(Graphics g) {
            Graphics2D g2 = (Graphics2D) g.create();
            g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING,
                    RenderingHints.VALUE_ANTIALIAS_ON);
            int w = getWidth();
            int h = getHeight();
            if (fond != null) {
                g2.setColor(fond);
                g2.fillRoundRect(0, 0, w, h, rayon, rayon);
            }
            if (bordure != null) {
                g2.setColor(bordure);
                g2.setStroke(new BasicStroke(1f));
                g2.draw(new java.awt.geom.RoundRectangle2D.Double(
                        0.5, 0.5, w - 1, h - 1, rayon, rayon));
            }
            g2.dispose();
        }
    }

